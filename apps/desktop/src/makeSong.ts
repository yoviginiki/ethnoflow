/** What "Make the song" decided and why: shown to the user, line by line. */
export interface MakeFact {
  key: keyof Messages;
  detail?: string;
}

export interface MakeSongResult {
  takeId: string;
  facts: MakeFact[];
  scale: Scale | null;
  bpm: number | null;
  detectedBpm: number | null;
  sections: number;
}

const NOTE_NAMES_PC = 12;

function pcHistogram(notes: Note[]): { pc: number; share: number }[] {
  const h = new Array<number>(NOTE_NAMES_PC).fill(0);
  let tot = 0;
  for (const n of notes) {
    const d = Math.max(0, n.end - n.start);
    h[((n.midi % 12) + 12) % 12] += d;
    tot += d;
  }
  return h.map((v, pc) => ({ pc, share: tot > 0 ? v / tot : 0 })).sort((a, b) => b.share - a.share);
}

/** Pick the take to build from: the loaded one, else the newest audio take. */
export function pickTake(p: ProjectView): string | null {
  if (p.loaded_take) return p.loaded_take;
  const audio = p.takes.filter((t) => t.state === "complete" && t.source !== "midi_file" && (t.duration_seconds ?? 0) > 2);
  return audio.length ? audio[audio.length - 1].id : null;
}

/**
 * Sections from the melody's own phrases: intro = the first phrase alone, then build /
 * drop / break / outro over the rest, each starting on a phrase boundary and snapped to a
 * bar. Roles carry energy and density, which the section follower turns into parts.
 */
export function sectionsFromPhrases(phrases: Phrase[], durationS: number, barS: number, ppq: number, bpm: number): SongMap["sections"] {
  const tps = (bpm / 60) * ppq;
  const snapBar = (s: number) => Math.max(0, Math.round(s / barS) * barS);
  const bounds = phrases.map((p) => p.start).filter((s) => s > 0.5);
  const nearest = (target: number) => {
    let best = target;
    let d = Infinity;
    for (const b of bounds) {
      const dd = Math.abs(b - target);
      if (dd < d) {
        d = dd;
        best = b;
      }
    }
    return snapBar(best);
  };
  const end = durationS;
  const introEnd = phrases.length > 1 ? snapBar(Math.min(phrases[1].start, end * 0.2)) : snapBar(Math.min(8 * barS, end * 0.2));
  const plan: [string, string, number, number, number][] = [
    ["intro", "intro", 0, 0.2, 0.3],
    ["build", "build", introEnd, 0.6, 0.6],
    ["drop", "drop", nearest(end * 0.45), 1.0, 0.9],
    ["break", "break", nearest(end * 0.75), 0.3, 0.3],
    ["outro", "outro", nearest(end * 0.9), 0.2, 0.2],
  ];
  // Keep boundaries strictly increasing and inside the take.
  const out: SongMap["sections"] = [];
  let last = 0;
  for (let i = 0; i < plan.length; i++) {
    const [name, role, startRaw, energy, density] = plan[i];
    const start = i === 0 ? 0 : Math.max(startRaw, last + barS);
    const nextStart = i + 1 < plan.length ? Math.max(plan[i + 1][2], start + barS) : end;
    const stop = Math.min(end, nextStart);
    if (stop - start < barS * 0.9 && i !== 0) continue;
    out.push({
      id: `s${i + 1}`,
      name,
      role,
      roles: [],
      start_tick: Math.round(start * tps),
      end_tick: Math.round(stop * tps),
      energy,
      density,
      tension: 0.5,
      locked: false,
      notes: "",
      transition_out: null,
    } as SongMap["sections"][number]);
    last = start;
    if (stop >= end) break;
  }
  if (out.length) out[out.length - 1].end_tick = Math.round(end * tps);
  return out;
}

/**
 * "Make the song": from one take, through the rule engines that already exist, to a
 * project that plays — scale from the take's hypotheses, tempo/meter and background from
 * the chosen starter, a song map from the melody's phrases, the take on a clean track.
 * Every decision is returned as a fact, so the assistant can explain it. Nothing here is
 * generated by hand-waving: the same calls the screens make, in one go.
 */
export async function makeSong(style: StarterId, takeIdWanted: string | null): Promise<MakeSongResult> {
  const st = useStore.getState();
  const lang = st.prefs.lang;
  const t = messages[lang];
  const facts: MakeFact[] = [];
  let p = st.project;
  if (!p) throw new Error(t.pickProjectFirst);
  const takeId = takeIdWanted ?? pickTake(p);
  if (!takeId) throw new Error(t.makeNoTake);
  // 1. The take and what it says.
  const info = await api.loadTake(takeId);
  st.setLoaded(info, null);
  const a = await api.analyzeTake();
  st.setAnalysis(a);
  const tempos: TempoCandidate[] = await api.estimateTakeTempo(null, null).catch(() => []);
  const detected = tempos.length && tempos[0].confidence >= 0.5 ? Math.round(tempos[0].bpm) : null;
  const hist = pcHistogram(a.notes);
  const top = a.hypotheses[0] ?? null;
  const scale: Scale | null = top ? scaleFromKind({ tonic_pc: top.tonic_pc, degrees_cents: [], kind: top.kind }) : null;
  facts.push({ key: "makeFactNotes", detail: `${a.notes.length} · ${hist.slice(0, 3).map((h) => `${t.noteNames[h.pc]} ${Math.round(h.share * 100)} %`).join(", ")}` });
  if (top) facts.push({ key: "makeFactKey", detail: `${t.noteNames[top.tonic_pc]} ${(t.scaleKinds as Record<string, string>)[top.kind] ?? top.kind} (${Math.round(top.probability * 100)} %)` });
  else facts.push({ key: "makeFactNoKey" });
  if (detected) facts.push({ key: "makeFactTempoDetected", detail: `${detected} BPM` });
  else facts.push({ key: "makeFactTempoNone" });
  // 2. Starter for the wanted style, in the take's key and register.
  const names = { noise: t.kindNoise, wind: t.kindWind, texture: t.kindTexture, bells: t.kindBells, pluck: t.kindPluck, loop: t.kindLoop, cloud: t.kindCloud, resonator: t.kindResonator, choir: t.kindChoir, bloom: t.kindBloom };
  if (!st.ambient) throw new Error(t.makeNoRack);
  const register = melodyRegister(a.notes);
  const starters = proposeStarters({ scale, timing: p.timing, detectedBpm: detected, register, baseRack: st.ambient, names });
  const starter = starters.find((s) => s.id === style) ?? starters[0];
  if (!starter) throw new Error(t.makeNoRack);
  if (JSON.stringify(scale) !== JSON.stringify(p.scale)) p = await api.setScale(scale);
  if (starter.timing && JSON.stringify(starter.timing) !== JSON.stringify(p.timing)) p = await api.setTiming(starter.timing);
  st.setProject(p);
  await applySession(starter.session, true);
  const bpm = p.timing.bpm;
  facts.push({ key: "makeFactStarter", detail: `${t[STARTER_TITLE[starter.id]]}${bpm ? ` · ${bpm} BPM ${p.timing.numerator}/${p.timing.unit}` : ""}` });
  if (detected && bpm && Math.abs(detected - bpm) > 3 && Math.abs(detected * 2 - bpm) > 3 && Math.abs(detected - bpm * 2) > 3) {
    facts.push({ key: "makeFactFreePhrase", detail: `${detected} ≠ ${bpm}` });
  }
  // 3. Song map from the melody's phrases.
  let sections = 0;
  if (bpm && p.timing.numerator && p.timing.unit) {
    const perf = await api.performanceAnalysis(st.prefs.intent).catch(() => null);
    const phrases = perf?.phrases ?? [];
    const barS = (60 / bpm) * p.timing.numerator * (4 / p.timing.unit);
    const dur = info.duration_seconds;
    const map: SongMap = { ...p.song_map, sections: sectionsFromPhrases(phrases, dur, barS, p.song_map.ppq, bpm) };
    if (map.sections.length >= 2) {
      p = await api.setSongMap(map);
      st.setProject(p);
      sections = map.sections.length;
      facts.push({ key: "makeFactMap", detail: `${sections} · ${phrases.length} ${t.livePhrases}` });
    }
  }
  // 4. The take on one clean track: aligned to the first note, lows cut, a little space.
  const firstOnset = a.notes.length ? Math.max(0, Math.min(...a.notes.map((n) => n.start)) - 0.05) : 0;
  const arrV = await api.arrangementGet();
  const arr: Arrangement = arrV.arrangement;
  const others = arr.tracks.filter((tr) => !tr.clips.some((c) => c.take_id === takeId));
  const melody = {
    id: arr.tracks.find((tr) => tr.clips.some((c) => c.take_id === takeId))?.id ?? `m${Date.now().toString(36)}`,
    name: t.makeMelodyTrack,
    gain_db: -1,
    pan: 0,
    mute: false,
    solo: false,
    lowpass_hz: 14000,
    highpass_hz: 140,
    send: 0.2,
    clips: [
      {
        id: `c${Date.now().toString(36)}`,
        take_id: takeId,
        start: 0,
        offset: firstOnset,
        length: Math.max(0.5, info.duration_seconds - firstOnset),
        gain_db: 0,
        fade_in: 0.03,
        fade_out: 1.0,
        mute: false,
      },
    ],
  } as Arrangement["tracks"][number];
  await api.setArrangement({ ...arr, tracks: [melody, ...others].slice(0, 8) });
  facts.push({ key: "makeFactTrack", detail: `HP 140 Hz · send 20 % · ${firstOnset.toFixed(2)} s` });
  // 5. Balance: render a window with stems, measure each group, move levels towards targets.
  try {
    facts.push(...(await balanceLevels(p, melody.id, info.duration_seconds)));
  } catch (e) {
    facts.push({ key: "makeFactBalanceSkipped", detail: String(e) });
  }
  facts.push({ key: "makeFactNext" });
  st.setLastMake({ takeId, facts, scale, bpm: bpm ?? null, detectedBpm: detected, sections });
  return { takeId, facts, scale, bpm: bpm ?? null, detectedBpm: detected, sections };
}

export const STARTER_TITLE: Record<StarterId, keyof Messages> = {
  quiet_ambient: "varQuietAmbient",
  dark_drone: "varDarkDrone",
  liquid_dnb: "varLiquidDnb",
  ambient_dnb: "varAmbientDnb",
  ethno_pulse: "varEthnoPulse",
};

/** RMS targets per group, dBFS (mono sum): melody on top, drums just under, bass below, beds far back. */
const TARGETS: Record<string, number> = { clips: -18, drums: -21, bass: -23, pad: -28, drone: -30, atmosphere: -30, extra: -30 };
const BALANCE_SECONDS = 16;

/**
 * Offline balance ("Auto Studio Engineer" lite): export the first seconds with stems
 * through the real graph, measure every stem, and correct the melody clip gain, the
 * drum/bass levels, the pad/drone levels and the extra parts towards the targets. One
 * pass, clamped, every number reported.
 */
async function balanceLevels(p: ProjectView, melodyTrackId: string, durationS: number): Promise<MakeFact[]> {
  const st = useStore.getState();
  const t = messages[st.prefs.lang];
  const dp = st.prefs.drone;
  const pp = st.prefs.pad;
  const dRoot = droneRoot(dp, p.scale, p.instrument);
  const pRoot = padRoot(pp, dp, p.scale, p.instrument);
  const padNotes = pRoot === null ? null : voicingNotes(pp.voicing, pRoot, p.scale);
  const include = {
    clips: true,
    drone: st.layers.drone && dRoot !== null ? droneSettings(dp, dRoot) : null,
    pad: st.layers.pad && padNotes ? padSettings(pp, padNotes) : null,
    ambient: st.layers.ambient,
    rhythm: st.layers.rhythm ? { ...st.prefs.rhythm, chord: st.padChord, root_midi: dRoot, intonation: dp.intonation } : null,
  };
  const out = `${p.root}/trash/_balance.wav`;
  const r = await api.exportSong(out, include as never, st.prefs.exportFormat, null, Math.min(BALANCE_SECONDS, Math.max(4, durationS)), true);
  const stats = await api.wavStats(r.stems, null, null);
  const group = (path: string) => {
    const base = path.replace(/\\/g, "/").split("/").pop() ?? "";
    const name = base.replace(/\.wav$/, "");
    return name in TARGETS ? name : "extra";
  };
  const by = new Map<string, number>();
  for (const s of stats) {
    const g = group(s.path);
    if (s.rms_dbfs > -100) by.set(g, Math.max(by.get(g) ?? -200, s.rms_dbfs));
  }
  const clamp = (x: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, x));
  const line: string[] = [];
  const clipsRms = by.get("clips");
  if (clipsRms !== undefined) {
    const delta = clamp(TARGETS.clips - clipsRms, -18, 12);
    const v = await api.arrangementGet();
    const tracks = v.arrangement.tracks.map((tr) => (tr.id === melodyTrackId ? { ...tr, clips: tr.clips.map((c) => ({ ...c, gain_db: clamp(c.gain_db + delta, -24, 12) })) } : tr));
    await api.setArrangement({ ...v.arrangement, tracks });
    line.push(`${t.makeMelodyTrack} ${clipsRms.toFixed(0)}→${(clipsRms + delta).toFixed(0)}`);
  }
  const rh = { ...st.prefs.rhythm };
  const drumsRms = by.get("drums");
  if (drumsRms !== undefined && rh.drums.on) {
    const delta = clamp(TARGETS.drums - drumsRms, -12, 14);
    rh.drums = { ...rh.drums, level_db: clamp(rh.drums.level_db + delta, -36, 6) };
    line.push(`${t.drumsTitle} ${drumsRms.toFixed(0)}→${(drumsRms + delta).toFixed(0)}`);
  }
  const bassRms = by.get("bass");
  if (bassRms !== undefined && rh.bass.on) {
    const delta = clamp(TARGETS.bass - bassRms, -12, 14);
    rh.bass = { ...rh.bass, level_db: clamp(rh.bass.level_db + delta, -36, 6) };
    line.push(`${t.bassTitle} ${bassRms.toFixed(0)}→${(bassRms + delta).toFixed(0)}`);
  }
  const extraRms = by.get("extra");
  if (extraRms !== undefined && (rh.extras ?? []).some((x) => x.on)) {
    const delta = clamp(TARGETS.extra - extraRms, -12, 10);
    rh.extras = (rh.extras ?? []).map((x) => ({ ...x, level_db: clamp(x.level_db + delta, -40, 0) }));
    line.push(`${t.rackTitle} ${extraRms.toFixed(0)}→${(extraRms + delta).toFixed(0)}`);
  }
  st.setPref("rhythm", rh);
  const padRms = by.get("pad");
  if (padRms !== undefined) {
    const delta = clamp(TARGETS.pad - padRms, -12, 10);
    st.setPref("pad", { ...pp, levelDb: clamp(pp.levelDb + delta, -40, 0) });
    line.push(`${t.pad} ${padRms.toFixed(0)}→${(padRms + delta).toFixed(0)}`);
  }
  const droneRms = by.get("drone");
  if (droneRms !== undefined) {
    const delta = clamp(TARGETS.drone - droneRms, -12, 10);
    st.setPref("drone", { ...dp, levelDb: clamp(dp.levelDb + delta, -40, 0) });
    line.push(`${t.drone} ${droneRms.toFixed(0)}→${(droneRms + delta).toFixed(0)}`);
  }
  return [{ key: "makeFactBalance", detail: line.join(" · ") + " dBFS" }];
}
